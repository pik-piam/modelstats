"""``ns.DEFAULT`` reproduces ``stri_order(numeric = TRUE)`` on every sort golden.

The goldens under ``migration/goldens/sort`` were generated by ``migration/harness/make_goldens.R``
(``fam_sort``) inside the sandbox, i.e. under ``LC_ALL=C.utf8``, where stringi's default collator
locale is ``en_US_POSIX`` (``migration/02-python-libraries.md`` section 4.4). Each golden records the
sorted names (``value``) and the 1-based permutation R returned (``order``); the Python side must
reproduce both with the fixed flags of decision D-14 (``migration/03-migration-plan.md`` section 3.5),
the case-sensitive ``ns.DEFAULT``. The one accepted deviation is ``exotic``: D-14 records non-ASCII
names "as they fall", and natsort places ``ä``, ``ß`` and ``ﬁ`` differently from ICU; the ASCII
subsequence must still agree.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from natsort import index_natsorted, natsorted, ns

pytestmark = pytest.mark.golden

MATCHING = (
    "amt-names",
    "cli-list",
    "coupled",
    "coupled-9-10-11",
    "duplicates",
    "empty",
    "single",
    "sortroot",
)
DEVIATING = ("exotic",)


def case_names(cases_dir: Path, case_id: str) -> list[str]:
    case = json.loads((cases_dir / "sort" / f"{case_id}.json").read_text(encoding="utf-8"))
    names: list[str] = case["names"]
    return names


def golden(goldens_dir: Path, case_id: str) -> tuple[list[str], list[int]]:
    data = json.loads((goldens_dir / "sort" / f"{case_id}.json").read_text(encoding="utf-8"))
    assert "error" not in data, data
    value: list[str] = data["value"]
    order: list[int] = data["order"]
    return value, order


def test_every_sort_golden_is_listed_here(cases_dir: Path, goldens_dir: Path) -> None:
    on_disk = {path.stem for path in (goldens_dir / "sort").glob("*.json")}
    assert on_disk == {path.stem for path in (cases_dir / "sort").glob("*.json")}
    assert on_disk == set(MATCHING) | set(DEVIATING)


@pytest.mark.parametrize("case_id", MATCHING)
def test_default_flags_reproduce_the_golden(case_id: str, cases_dir: Path, goldens_dir: Path) -> None:
    names = case_names(cases_dir, case_id)
    value, order = golden(goldens_dir, case_id)
    assert value == [names[i - 1] for i in order]
    assert natsorted(names, alg=ns.DEFAULT) == value
    assert [i + 1 for i in index_natsorted(names, alg=ns.DEFAULT)] == order


def test_amt_names_keep_uppercase_before_lowercase(cases_dir: Path, goldens_dir: Path) -> None:
    """The finding's counterexample: EU21 before EcBudg500, and every SSP* before archive/*."""
    value, _ = golden(goldens_dir, "amt-names")
    ours = natsorted(case_names(cases_dir, "amt-names"), alg=ns.DEFAULT)
    assert ours == value
    eu21 = ours.index("SSP2-EU21-NPi2025-AMT_2026-09-18_22.11.36")
    ec_budg = ours.index("SSP2-EcBudg500-AMT_2026-09-19_01.25.14")
    assert eu21 < ec_budg
    archive = ours.index("archive/default-AMT_2026-06-27_00.53.26")
    assert all(ours.index(n) < archive for n in ours if n.startswith("SSP"))


def test_exotic_deviates_only_in_non_ascii_names(cases_dir: Path, goldens_dir: Path) -> None:
    """D-14: non-ASCII names are recorded as they fall; the ASCII part of the order still matches R."""
    names = case_names(cases_dir, "exotic")
    value, _ = golden(goldens_dir, "exotic")
    ours = natsorted(names, alg=ns.DEFAULT)
    assert {n for n in names if not n.isascii()} == {"Ä", "ä", "é", "ß", "ﬁ"}
    assert [n for n in ours if n.isascii()] == [n for n in value if n.isascii()]
    # ICU puts ä right after Z (before "a 1"); natsort puts it after a_1. ICU ends ﬁ, ß; natsort ß, ﬁ.
    assert value.index("ä") == value.index("Z") + 1
    assert ours.index("ä") == ours.index("a_1") + 1
    assert value[-2:] == ["ﬁ", "ß"]
    assert ours[-2:] == ["ß", "ﬁ"]
    # Ä and é fall in the same place under both.
    assert value.index("Ä") == ours.index("Ä")
    assert value.index("é") == ours.index("é")
