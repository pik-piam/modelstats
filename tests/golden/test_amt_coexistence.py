def test_r_start_then_python_evaluate() -> None:
    run = run_scenario(
        "r-start-py-evaluate",
        f"echo next:start > {STATUS_FILE}\n",
        f"""snapshot pre
r_step r_start '{START_TIME}'
snapshot after_r_start
py_step py_evaluate '{EVAL_TIME}'
snapshot after_py_evaluate
""",
    )
    assert run.status == 0
    assert_step_ok(run, "r_start", START_FINISHED)
    after_start = run.snapshot("after_r_start")
    assert after_start.testsstatus == "next:evaluate"
    assert_step_ok(run, "py_evaluate", EVALUATE_FINISHED)
    after = run.snapshot("after_py_evaluate")
    assert after.testsstatus == "next:start"
    # the Python evaluate read R's runsToStart.rds and runcode.rds (unchanged by it) and wrote the rest
    assert after.hashes["runsToStart.rds"] == after_start.hashes["runsToStart.rds"]
    assert after.hashes["runcode.rds"] == after_start.hashes["runcode.rds"]
    assert after.hashes["lastcommit.rds"] != after_start.hashes["lastcommit.rds"]
    assert_state_readable(
        after, "lastcommit_rds.json", "runcode_rds.json", "runsToStart_rds.json", "output_gRS_rds.json"
    )
    assert after.dumps["lastcommit_rds.json"]["value"] == ["3f5e2a1b9c8d7e6f5a4b3c2d1e0f9a8b7c6d5e4f"]
    assert after.dumps["runcode_rds.json"]["value"] == [".*-AMT_2026-09-28|.*-AMT_2026-09-29"]
    assert after.tmpfiles == []


def test_python_start_then_r_evaluate() -> None:
    run = run_scenario(
        "py-start-r-evaluate",
        f"echo next:start > {STATUS_FILE}\n",
        f"""snapshot pre
py_step py_start '{START_TIME}'
snapshot after_py_start
r_step r_evaluate '{EVAL_TIME}'
snapshot after_r_evaluate
""",
    )
    assert run.status == 0
    assert_step_ok(run, "py_start", START_FINISHED)
    after_start = run.snapshot("after_py_start")
    assert after_start.testsstatus == "next:evaluate"
    assert_state_readable(after_start, "runcode_rds.json", "runsToStart_rds.json")
    assert after_start.dumps["runcode_rds.json"]["value"] == [".*-AMT_2026-09-28|.*-AMT_2026-09-29"]
    rows = _rows(after_start.dumps["runsToStart_rds.json"])
    assert rows and all(str(row["_row"]).endswith("-AMT") for row in rows)
    assert_step_ok(run, "r_evaluate", EVALUATE_FINISHED)
    after = run.snapshot("after_r_evaluate")
    assert after.testsstatus == "next:start"
    assert after.hashes["runsToStart.rds"] == after_start.hashes["runsToStart.rds"]
    assert after.hashes["lastcommit.rds"] != after_start.hashes["lastcommit.rds"]
    assert_state_readable(after, "lastcommit_rds.json", "output_gRS_rds.json")
    assert after.tmpfiles == []


def test_python_cycle_r_cycle_python_cycle() -> None:
    steps = "snapshot pre\n"
    plan = [
        ("py_start_1", "py_step", START_TIME),
        ("py_evaluate_1", "py_step", EVAL_TIME),
        ("r_start_2", "r_step", START_TIME),
        ("r_evaluate_2", "r_step", EVAL_TIME),
        ("py_start_3", "py_step", START_TIME),
        ("py_evaluate_3", "py_step", EVAL_TIME),
    ]
    for name, fn, when in plan:
        steps += f"{fn} {name} '{when}'\nsnapshot after_{name}\n"
    run = run_scenario("py-r-py-cycles", f"echo next:start > {STATUS_FILE}\n", steps)
    assert run.status == 0
    for name, _fn, _when in plan:
        finished = START_FINISHED if "start" in name else EVALUATE_FINISHED
        assert_step_ok(run, name, finished)
        snap = run.snapshot(f"after_{name}")
        assert snap.testsstatus == ("next:evaluate" if "start" in name else "next:start"), name
        assert_state_readable(
            snap, "lastcommit_rds.json", "runcode_rds.json", "runsToStart_rds.json", "output_gRS_rds.json"
        )
        assert snap.tmpfiles == [], name
    # the gRS history keeps its rows across the three writers (R's rbind on the Python table and back)
    names = [
        {str(row["_row"]) for row in _rows(run.snapshot(f"after_{name}").dumps["output_gRS_rds.json"])}
        for name in ("py_evaluate_1", "r_evaluate_2", "py_evaluate_3")
    ]
    assert names[0] <= names[1] <= names[2], names


def test_interrupted_python_evaluate_leaves_the_pre_cycle_state() -> None:
    run = run_scenario(
        "interrupted-py-evaluate",
        "true\n",
        f"""snapshot pre
interrupt_py_step py_evaluate '{EVAL_TIME}' '{ANALYSIS_MARKER}'
snapshot after_interrupt
set_status next:evaluate
r_step r_evaluate '{EVAL_TIME}'
snapshot after_r_evaluate
""",
    )
    assert run.status == 0
    assert (run.out / "py_evaluate.killed").read_text().strip() == "1", "the evaluate was not interrupted"
    err = run.step_err("py_evaluate")
    assert ANALYSIS_MARKER in err and EVALUATE_FINISHED not in err
    pre, after = run.snapshot("pre"), run.snapshot("after_interrupt")
    for name in ("lastcommit.rds", "runcode.rds", "runsToStart.rds"):
        assert after.hashes[name] == pre.hashes[name], name
    assert after.testsstatus == RUNNING
    assert_state_readable(after, "output_gRS_rds.json")
    assert after.dumps["output_gRS_rds.json"]["class"] == "data.frame"  # jsonlite auto_unbox: a scalar
    assert after.tmpfiles == []
    # the R rollback resumes from that state once the operator resets the marker
    assert_step_ok(run, "r_evaluate", EVALUATE_FINISHED)
    final = run.snapshot("after_r_evaluate")
    assert final.testsstatus == "next:start"
    assert final.hashes["lastcommit.rds"] != pre.hashes["lastcommit.rds"]


def test_partial_write_temp_file_left_behind_is_ignored_by_both() -> None:
    temp_files = (f"{MYDIR}output/.gRS.rds.0123456789ab.tmp", f"{MYDIR}.lastcommit.rds.0123456789ab.tmp")
    prepare = "".join(f"printf 'partial write' > {p}\n" for p in temp_files)
    run = run_scenario(
        "partial-write",
        prepare,
        f"""snapshot pre
py_step py_evaluate '{EVAL_TIME}'
snapshot after_py_evaluate
set_status next:evaluate
r_step r_evaluate '{EVAL_TIME}'
snapshot after_r_evaluate
""",
    )
    assert run.status == 0
    assert sorted(run.snapshot("pre").tmpfiles) == sorted(Path(p).name for p in temp_files)
    assert_step_ok(run, "py_evaluate", EVALUATE_FINISHED)
    after_py = run.snapshot("after_py_evaluate")
    assert after_py.testsstatus == "next:start"
    assert_state_readable(after_py, "lastcommit_rds.json", "output_gRS_rds.json")
    assert sorted(after_py.tmpfiles) == sorted(Path(p).name for p in temp_files)
    assert_step_ok(run, "r_evaluate", EVALUATE_FINISHED)
    after_r = run.snapshot("after_r_evaluate")
    assert after_r.testsstatus == "next:start"
    assert_state_readable(after_r, "lastcommit_rds.json", "output_gRS_rds.json")
    assert sorted(after_r.tmpfiles) == sorted(Path(p).name for p in temp_files)


@pytest.mark.parametrize("corrupt", ["output/gRS.rds", "lastcommit.rds"])
def test_corrupt_state_file_fails_identically(corrupt: str) -> None:
    tag = corrupt.replace("/", "-").replace(".", "-")
    run = run_scenario(
        f"corrupt-{tag}",
        f"echo garbage > {MYDIR}{corrupt}\n",
        f"""snapshot pre
py_step py_evaluate '{EVAL_TIME}'
snapshot after_py_evaluate
set_status next:evaluate
r_step r_evaluate '{EVAL_TIME}'
snapshot after_r_evaluate
""",
    )
    assert run.status == 0
    pre = run.snapshot("pre")
    for step, snap_name in (("py_evaluate", "after_py_evaluate"), ("r_evaluate", "after_r_evaluate")):
        assert run.step_status(step) == 1, f"{step}: status {run.step_status(step)}\n{run.step_err(step)[-2000:]}"
        assert UNKNOWN_FORMAT in run.step_err(step), f"{step}: R's error text missing\n{run.step_err(step)[-2000:]}"
        assert "Execution halted" in run.step_err(step)
        snap = run.snapshot(snap_name)
        assert snap.testsstatus == RUNNING, step
        for name in ("lastcommit.rds", "runcode.rds", "runsToStart.rds"):
            assert snap.hashes[name] == pre.hashes[name], f"{step}: {name} changed"
        assert snap.tmpfiles == [], step
    # both implementations left the same tree behind (the corrupt file included: neither rewrote it)
    after_py, after_r = run.snapshot("after_py_evaluate"), run.snapshot("after_r_evaluate")
    assert after_py.hashes == after_r.hashes == pre.hashes
    assert after_py.testsstatus == after_r.testsstatus
